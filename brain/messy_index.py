# ============================================================================ model calls
def ask(llm, prompt, kw, think, seed):
    body = {"model": llm.model, "messages": [{"role": "user", "content": prompt}],
            "chat_template_kwargs": {"enable_thinking": think}, "seed": seed, **kw}
    t0 = time.time()
    r = llm.request("POST", "/chat/completions", body)
    ch = r["choices"][0]
    msg = ch.get("message") or {}
    content, reasoning = msg.get("content") or "", msg.get("reasoning") or msg.get("reasoning_content") or ""
    if "</think>" in content:
        reasoning, content = reasoning + content.split("</think>")[0], content.split("</think>")[-1]
    cut = ch.get("finish_reason") == "length"
    u = r.get("usage") or {}
    return {"text": "" if (think and cut) else content.strip(), "thinking": reasoning, "cut": cut,
            "prompt_tokens": u.get("prompt_tokens") or 0, "completion_tokens": u.get("completion_tokens") or 0,
            "sec": round(time.time() - t0, 2)}


class Embedder:
    def __init__(self):
        from fastembed import TextEmbedding
        self.m, self.cache, self.lock = TextEmbedding(EMB_MODEL), {}, threading.Lock()

    def __call__(self, texts):
        with self.lock:
            todo = [t for t in dict.fromkeys(texts) if t not in self.cache]
            if todo:
                for t, v in zip(todo, self.m.embed(todo)):
                    self.cache[t] = v / (np.linalg.norm(v) + 1e-9)
            return np.array([self.cache[t] for t in texts]) if texts else np.zeros((0, 384))


def norm(s):
    return re.sub(r"[^a-z0-9 ]", " ", s.lower()).split()


# ============================================================================ the index
class Index:
    """Rows only ever added (and removed with their message on deletion); people are ids with the names seen."""

    def __init__(self):
        self.rows, self.people, self.lock = [], {}, threading.Lock()

    def person(self, full):
        pid = f"P{len(self.people) + 1}"
        self.people[pid] = {"full": full.strip(), "names": {full.strip().lower()}}
        first = full.strip().split()[0].lower() if full.strip() else ""
        if first:
            self.people[pid]["names"].add(first)
        return pid

    def find_full(self, name):
        name = name.strip().lower()
        hits = [pid for pid, p in self.people.items() if p["full"].lower() == name]
        return hits[0] if len(hits) == 1 else None

    def add(self, note, pid, kind, value, link=None):
        kind, value = kind.strip().lower(), value.strip()
        self.rows.append({"note": note, "pid": pid, "kind": kind, "value": value, "link": link})
        p = self.people[pid]
        if kind == "nickname" and value:
            p["names"].add(value.strip('"').lower())
        if kind in ("relation to me", "relation") and value:
            p["names"].add(f"my {value.lower().replace('my ', '')}")

    def delete(self, note_ids):
        self.rows = [r for r in self.rows if r["note"] not in note_ids]

    def summary(self, pid):
        p = self.people[pid]
        names = sorted(n for n in p["names"] if n != p["full"].lower())
        rel = [r for r in self.rows if r["pid"] == pid and r["kind"] in ("relation to me", "known from")][:2]
        links = [r for r in self.rows if r["pid"] == pid and r["link"]][:3]
        bits = [p["full"]] + ([f'also {", ".join(names[:4])}'] if names else [])
        bits += [f'{r["kind"]}: {r["value"]}' for r in rel]
        bits += [f'{r["kind"]}: {r["link"]} {self.people[r["link"]]["full"]}' for r in links if r["link"] in self.people]
        return f"{pid}: " + "; ".join(bits)


def note_line(n):
    return f"#{n['id']} [{n['date']}] {n['text']}"


def candidates(ix, chunk, recent):
    """People to show the writer: names, nicknames and "my X" phrases in the new or context messages, the people
    mentioned most recently (pronouns), and the people linked to them ("Kofi's flatmate")."""
    text = " ".join(n["text"] for n in chunk).lower()
    words = set(norm(text))
    score = Counter()
    for pid, p in ix.people.items():
        for nm in p["names"]:
            toks = nm.split()
            if nm.startswith("my ") and nm in text:
                score[pid] += 3
            elif len(toks) > 1 and nm in text:
                score[pid] += 3
            elif len(toks) == 1 and toks[0] in words:
                score[pid] += 1
    for k, pid in enumerate(reversed(recent[-12:])):
        score[pid] += 0.5
    top = [pid for pid, _ in score.most_common(CANDIDATES)]
    linked = {r["link"] for r in ix.rows if r["pid"] in top[:10] and r["link"]} | \
             {r["pid"] for r in ix.rows if r["link"] in top[:10]}
    return (top + [p for p in linked if p not in top])[:CANDIDATES + 10]


ROW = re.compile(r"#\s*(\d+)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*(.+)")


def parse_rows(text, chunk_ids, ix, recent):
    """Apply the writer's lines to the index. Returns (rows added, lines that could not be used)."""
    added, bad, new_here = 0, 0, {}
    for line in text.splitlines():
        m = ROW.search(line)
        if not m:
            continue
        nid, who, kind, value = int(m.group(1)), m.group(2).strip(), m.group(3).strip(), m.group(4).strip()
        if nid not in chunk_ids:
            bad += 1
            continue
        pid = resolve(who, ix, new_here)
        if pid is None:
            bad += 1
            continue
        link = None
        vm = re.fullmatch(r"(P\d+)\b.*", value)
        if vm and vm.group(1) in ix.people:
            link = vm.group(1)
        elif value.upper().startswith("NEW"):
            link = resolve(value, ix, new_here)
        elif kind.lower() not in ("event", "nickname", "relation to me", "known from") and ix.find_full(value):
            link = ix.find_full(value)
        ix.add(nid, pid, kind, value, link)
        recent.append(pid)
        added += 1
    return added, bad


def resolve(who, ix, new_here):
    w = who.strip()
    m = re.match(r"(P\d+)\b", w)
    if m:
        return m.group(1) if m.group(1) in ix.people else None
    m = re.match(r"NEW\s*:?\s*(.+)", w, re.I)
    name = (m.group(1) if m else w).strip().strip('"')
    if not name:
        return None
    key = name.lower()
    if key in new_here:
        return new_here[key]
    hit = ix.find_full(name)
    if hit:
        return hit
    if not m:                    # a bare name that is not a known full name: treat it as new only if it looks like one
        if len(name.split()) < 2:
            return None
    pid = ix.person(name)
    new_here[key] = pid
    return pid


def build_index(llm, W, path, log):
    """B's write side: messages in order, CHUNK at a time, thinking off. Resumable from the log of replies."""
    ix, recent, stats = Index(), [], Counter()
    done = {}
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            r = json.loads(line)
            done[r["chunk"]] = r
    f = open(path, "a", encoding="utf-8")
    notes = W.notes
    t0 = time.time()
    for c0 in range(0, len(notes), CHUNK):
        chunk = notes[c0:c0 + CHUNK]
        ids = {n["id"] for n in chunk}
        if c0 in done:
            r = done[c0]
        else:
            ctx = notes[max(0, c0 - CONTEXT):c0]
            cands = candidates(ix, ctx + chunk, recent)
            prompt = WRITE.format(people="\n".join(ix.summary(p) for p in cands) or "(none yet)",
                                  context="\n".join(note_line(n) for n in ctx) or "(none)",
                                  new="\n".join(note_line(n) for n in chunk))
            r = ask(llm, prompt, WRITE_KW, False, c0)
            r = {"chunk": c0, "text": r["text"], "cut": r["cut"], "prompt_tokens": r["prompt_tokens"],
                 "completion_tokens": r["completion_tokens"], "sec": r["sec"], "candidates": len(cands)}
            f.write(json.dumps(r, ensure_ascii=True) + "\n")
            f.flush()
        a, b = parse_rows(r["text"], ids, ix, recent)
        stats["rows"] += a
        stats["bad_lines"] += b
        stats["cut"] += r["cut"]
        stats["prompt_tokens"] += r["prompt_tokens"]
        stats["completion_tokens"] += r["completion_tokens"]
        if c0 % (CHUNK * 25) == 0:
            log(f"index: {c0 + len(chunk)}/{len(notes)} messages, {len(ix.people)} people, {len(ix.rows)} rows, "
                f"{(time.time() - t0) / 60:.1f} min")
    stats["notes"] = len(notes)
    return ix, dict(stats)


def oracle_index(W):
    """The same kind of index, built from the truth: correct people, canonical kinds and values."""
    ix = Index()
    pid_of = {}
    for p in W.people:
        pid_of[p["id"]] = ix.person(p["full"])
    for n in W.notes:
        for pid, kind, value in n["facts"]:
            x = pid_of[pid]
            if kind in MW.RELS:
                ix.add(n["id"], x, kind, pid_of[value], link=pid_of[value])
            elif kind == "event":
                ix.add(n["id"], x, "event", f"{value[1]} {value[0]}")
            elif kind in MW.SLOTS:
                if value is None:
                    ix.add(n["id"], x, kind, "none")
                else:
                    alt = next(a for c, a, _ in MW.SLOTS[kind]["vals"] if c == value)
                    ix.add(n["id"], x, kind, value if alt == value else f"{value} ({alt})")
            else:
                ix.add(n["id"], x, kind, str(value))
    return ix


