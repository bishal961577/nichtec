class Search:
    def __init__(self, W, emb):
        self.notes = [n for n in W.notes if n["id"] not in W.deleted_ids]
        self.bm = BM25([n["text"] for n in self.notes])
        self.vec = emb([n["text"] for n in self.notes])
        self.emb = emb

    def top(self, query, k=AGENT_K):
        b = self.bm.top(query, 100)                                      # (BM25.top returns indices in notebook order)
        q = [t for t in query.lower().split()]
        bm_scores = []
        for i in b:
            tf, d = self.bm.tf[i], self.bm.toks[i]
            bm_scores.append((sum(self.bm.idf.get(t, 0) * tf[t] * (self.bm.k1 + 1) / (tf[t] + self.bm.k1 * (
                1 - self.bm.b + self.bm.b * len(d) / self.bm.avg)) for t in set(q) if t in tf), i))
        bm_rank = [i for _, i in sorted(bm_scores, reverse=True)]
        sims = self.vec @ self.emb([query])[0]
        em_rank = list(np.argsort(-sims)[:100])
        rrf = Counter()
        for rank in (bm_rank, em_rank):
            for k_, i in enumerate(rank):
                rrf[int(i)] += 1 / (60 + k_)
        return [self.notes[i]["id"] for i, _ in rrf.most_common(k)]


def run_agent(llm, S, W, q, think, seed):
    found, steps, tokens = list(S.top(q["q"])), [], 0
    by = {n["id"]: n for n in W.notes}
    for left in range(AGENT_ROUNDS, -1, -1):
        notes = "\n".join(f"[{by[i]['date']}] {by[i]['text']}" for i in sorted(found))
        if left == 0:
            r = ask(llm, ANSWER.format(notes=notes, today=TODAY, q=q["q"]), THINK if think else NOTHINK, think, seed)
            steps.append({"final": True, **{k: r[k] for k in ("text", "cut", "completion_tokens")}})
            return r, found, steps
        r = ask(llm, AGENT.format(notes=notes, today=TODAY, q=q["q"], left=left), THINK if think else NOTHINK, think,
                seed + left)
        steps.append({k: r[k] for k in ("text", "cut", "completion_tokens")})
        t = r["text"]
        m = re.search(r"SEARCH:\s*(.+)", t)
        if m and "ANSWER:" not in t.split("SEARCH:")[0]:
            for i in S.top(m.group(1).strip().splitlines()[0]):
                if i not in found:
                    found.append(i)
            found = found[:MAX_NOTES]
            continue
        a = re.search(r"ANSWER:\s*(.+)", t, re.S)
        r = dict(r, text=(a.group(1).strip() if a else t))
        return r, found, steps
    return r, found, steps


# ============================================================================ pages (the reading ceiling)
def pages(W, q):
    rng = random.Random(zlib.crc32(q["qid"].encode()))
    gold = set(q["notes"])
    about = set([q["person"]] if q["person"] is not None else []) | set(q.get("people", [])) | \
        ({q["anchor"]} if q.get("anchor") is not None else set())
    if q["person"] is not None:
        same = [p["id"] for p in W.people if p["first"] == W.people[q["person"]]["first"]]
        about |= set(same)
    pool = [n["id"] for n in W.notes if n["id"] not in gold and n["id"] not in W.deleted_ids and
            any(m[1] in about for m in n["mentions"])]
    if q["kind"] == "upd":                         # the whole history of the asked fact belongs in the pages
        gold |= set(W.current(q["person"], q["slot"])[2])
    return sorted(gold | set(rng.sample(pool, min(20, len(pool)))))


