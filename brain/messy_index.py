def candidates(ix, chunk, recent):
    """People to show the writer: names, nicknames and "my X" phrases in the new or context messages, the people
    mentioned most recently (pronouns), and the people linked to them ("Kofi's flatmate")."""
    text = " ".join(n["text"] for n in chunk).lower()
    words = set(norm(text))
    score = Counter()
    for pid, p in ix.people.items():
        for nm in p["names"]:
            toks = nm.split()
            if nm.startswith("my ") and (nm in text or ("my old " + nm[3:]) in text):
                score[pid] += 3
            elif len(toks) > 1 and nm in text:
                score[pid] += 3
            elif len(toks) == 1 and toks[0] in words:
                score[pid] += 1
    named = set(score)                                   # matched by a name: their links come along ("Kofi's flatmate")
    poss = {pid for pid, p in ix.people.items() for nm in p["names"] if (nm + "'s ") in text}
    for k, pid in enumerate(reversed(recent[-12:])):
        score[pid] += 0.5
    num = lambda x: int(x[1:])
    top = sorted(score, key=lambda x: (-score[x], num(x)))[:CANDIDATES]
    partner = Counter()
    for r in ix.rows:
        if r["link"]:
            if r["pid"] in named:
                partner[r["link"]] += 1
            if r["link"] in named:
                partner[r["pid"]] += 1
    nouns = defaultdict(set)                             # "Kofi's flatmate": the word after the possessive
    for pid, p in ix.people.items():
        for nm in p["names"]:
            for m in re.finditer(re.escape(nm) + r"'s (\w+(?: \w+)?)", text):
                nouns[pid].update(norm(m.group(1)))
    first = Counter()
    for r in ix.rows:
        if r["link"] and (r["pid"] in poss or r["link"] in poss):
            anchor = r["pid"] if r["pid"] in poss else r["link"]
            other = r["link"] if r["pid"] in poss else r["pid"]
            fits = any(w[:5] in r["kind"] for w in nouns.get(anchor, ()) if len(w) > 3)
            first[other] += 10 if fits else 1
    extra = sorted((x for x in first if x not in top), key=lambda x: (-first[x], num(x)))
    extra += sorted((x for x in partner if x not in top and x not in first), key=lambda x: (-partner[x], num(x)))
    return top + extra[:LINKED]


def via_links(ix, chunk, cap=12):
    """For "Kofi's flatmate" in the new messages: Kofi's link rows whose kind fits "flatmate", shown to the writer as
    rows (both directions, so it can check). The index answering who someone is through another person (dev phase:
    candidate list, allowed)."""
    text = " ".join(n["text"] for n in chunk).lower()
    out = []
    for pid, p in ix.people.items():
        for nm in p["names"]:
            if len(nm) < 3 or (nm + "'s ") not in text:
                continue
            for m in re.finditer(re.escape(nm) + r"'s (\w+(?: \w+)?)", text):
                words = [w for w in norm(m.group(1)) if len(w) > 3]
                for r in ix.rows:
                    if r["link"] and pid in (r["pid"], r["link"]) and r["link"] in ix.people and \
                            any(w[:5] in r["kind"].lower() for w in words):
                        line = (f'"{m.group(0)}": {ix.people[r["pid"]]["full"]} ({r["pid"]}) | {r["kind"]} | '
                                f'{ix.people[r["link"]]["full"]} ({r["link"]})')
                        if line not in out:
                            out.append(line)
    return out[:cap]


ROW = re.compile(r"#\s*(\d+)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*(.+)")
ROW3 = re.compile(r"#\s*(\d+)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*$")   # dev phase (parsing): "#267 | P16 | plays trumpet"


def fix_citation(nid, kind, value, texts):
    """If the cited message does not contain the row's value but exactly one other message of the chunk does, the row
    belongs to that one (a deleted message must take its rows with it)."""
    words = [w for w in norm(value) if len(w) > 2 and w not in ("none", "the", "and")]
    if not words or kind.lower() in ("mentioned", "event") or re.fullmatch(r"P\d+.*", value) or nid not in texts:
        return nid
    has = lambda t: all(w in norm(t) for w in words)
    if has(texts[nid]):
        return nid
    others = [i for i, t in texts.items() if i != nid and has(t)]
    return others[0] if len(others) == 1 else nid


def parse_rows(text, chunk_ids, ix, recent, texts=None):
    """Apply the writer's lines to the index. Returns (rows added, lines that could not be used)."""
    added, bad, new_here = 0, 0, {}
    for line in text.splitlines():
        m = ROW.search(line)
        if m:
            nid, who, kind, value = int(m.group(1)), m.group(2).strip(), m.group(3).strip(), m.group(4).strip()
        else:
            m = ROW3.search(line)
            if not m:
                continue
            nid, who, kind, value = int(m.group(1)), m.group(2).strip(), "note", m.group(3).strip()
        if nid not in chunk_ids:
            bad += 1
            continue
        if texts:
            nid = fix_citation(nid, kind, value, texts)
        kind, value = to_me(kind, value)
        said = reported(kind, value, ix)
        if said:                                          # "#n | Kofi | told me | Mira moved to Lyon" (dev phase: parsing)
            src = resolve(who, ix, new_here)
            if src:
                ix.add(nid, src, "mentioned", "-")
                added += 1
            who, kind, value = said
        if texts and nid in texts and value.strip() in ("", "-") and kind.lower() != "mentioned" and \
                re.search(r"\bmy " + re.escape(kind.lower()) + r"\b", texts[nid].lower()):
            kind, value = "relation to me", kind          # "#6 | NEW: Gaia Okafor | brother | -" (dev phase: parsing)
        pid = resolve(who, ix, new_here)
        if pid is None:
            bad += 1
            continue
        link = None
        vm = re.fullmatch(r"(P\d+)\b.*", value)
        if vm and vm.group(1) in ix.people:
            link = vm.group(1)
        elif value.upper().startswith("NEW"):
            link = resolve(value, ix, new_here)
        elif kind.lower() not in ("event", "nickname", "relation to me", "known from") and ix.find_full(value):
            link = ix.find_full(value)
        ix.add(nid, pid, kind, value, link)
        recent.append(pid)
        added += 1
    return added, bad


ME_WORDS = {"me", "myself", "i", "the writer", "the user", "user", "writer"}
REL_KINDS = {"relative", "relation", "relationship", "relation to user", "relation to writer", "relationship to me",
             "is my", "my"}


def to_me(kind, value):
    """Dev phase (parsing, allowed): the 4B writes "boss of | me" or "relative | grandma" for "relation to me"."""
    k, v = kind.strip().lower(), value.strip()
    m = re.fullmatch(r"(?:my |is my )?(.+?) (?:of|to)", k)
    if m and v.lower().strip(" .") in ME_WORDS:
        return "relation to me", m.group(1)
    if k in REL_KINDS and v and v != "-":
        return "relation to me", re.sub(r"^(my|is my)\s+", "", v, flags=re.I)
    return kind, value


SAID = re.compile(r"(told me|tells me|says|said|say|heard|mentioned that|told me that|says that|said that|news)$")


def reported(kind, value, ix):
    """A fact the 4B filed under the person who told me: "told me | Ivan Lopes juggles in the park". Returns
    (the id of the person it is about, "note", the rest) when the value starts with one known person's name."""
    if not SAID.search(kind.strip().lower()) or value.strip() in ("", "-"):
        return None
    v = re.sub(r"^(that|how)\s+", "", value.strip(), flags=re.I)
    best = None
    for pid, p in ix.people.items():
        for nm in p["names"]:
            if nm.startswith("my ") or len(nm) < 3:
                continue
            if re.match(re.escape(nm) + r"(?![a-z])", v.lower()) and (best is None or len(nm) > len(best[1])):
                best = (pid, nm)
    if best is None:
        return None
    same = [pid for pid, p in ix.people.items() if best[1] in p["names"]]
    if len(same) != 1:
        return None
    rest = v[len(best[1]):].strip(" ,:") or v
    return best[0], "note", rest


PRONOUNS = {"he", "she", "they", "him", "her", "them", "it", "his", "hers", "their"}


def resolve(who, ix, new_here):
    w = who.strip()
    m = re.match(r"(P\d+)\b", w)
    if m:
        return m.group(1) if m.group(1) in ix.people else None
    m = re.match(r"NEW\s*:?\s*(.+)", w, re.I)
    name = (m.group(1) if m else w).strip().strip('"')
    if not name or name.lower() in PRONOUNS:      # "NEW: He" is not a person (dev phase: parsing, allowed)
        return None
    key = name.lower()
    if key in new_here:
        return new_here[key]
    hit = ix.find_full(name)
    if hit:
        return hit
    if key.startswith("my "):    # "NEW: my brother" when someone is already "my brother" (dev phase: parsing)
        same = [pid for pid, p in ix.people.items() if key in p["names"]]
        if len(same) == 1:
            return same[0]
    if not m:                    # a bare name, nickname or "my sister": a known person if exactly one matches; else unusable
        same = [pid for pid, p in ix.people.items() if key in p["names"]]
        return same[0] if len(same) == 1 else None
    pid = ix.person(name)        # NEW: the writer says this is someone not yet in the index (a split if it is wrong)
    new_here[key] = pid
    return pid


def build_index(llm, W, path, log, think=False):
    """B's write side: messages in order, CHUNK at a time (thinking off; on for the thinking writer). Resumable from
    the log of replies."""
    ix, recent, stats = Index(), [], Counter()
    done = {}
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            r = json.loads(line)
            done[r["chunk"]] = r
    f = open(path, "a", encoding="utf-8")
    notes = W.notes
    t0 = time.time()
    for c0 in range(0, len(notes), CHUNK):
        chunk = notes[c0:c0 + CHUNK]
        ids = {n["id"] for n in chunk}
        if c0 in done:
            r = done[c0]
        else:
            ctx = notes[max(0, c0 - CONTEXT):c0]
            cands = candidates(ix, ctx + chunk, recent)
            prompt = WRITE.format(people="\n".join(ix.summary(p) for p in cands) or "(none yet)",
                                  links="\n".join(via_links(ix, chunk)) or "(none)",
                                  context="\n".join(note_line(n) for n in ctx) or "(none)",
                                  new="\n".join(note_line(n) for n in chunk))
            r = ask(llm, prompt, WRITE_KW_THINK if think else WRITE_KW, think, c0)
            r = {"chunk": c0, "text": r["text"], "cut": r["cut"], "prompt_tokens": r["prompt_tokens"],
                 "completion_tokens": r["completion_tokens"], "sec": r["sec"], "candidates": len(cands)}
            f.write(json.dumps(r, ensure_ascii=True) + "\n")
            f.flush()
        a, b = parse_rows(r["text"], ids, ix, recent, {n["id"]: n["text"] for n in chunk})
        stats["rows"] += a
        stats["bad_lines"] += b
        stats["cut"] += r["cut"]
        stats["prompt_tokens"] += r["prompt_tokens"]
        stats["completion_tokens"] += r["completion_tokens"]
        if c0 % (CHUNK * 25) == 0:
            log(f"index: {c0 + len(chunk)}/{len(notes)} messages, {len(ix.people)} people, {len(ix.rows)} rows, "
                f"{(time.time() - t0) / 60:.1f} min")
    stats["notes"] = len(notes)
    return ix, dict(stats)


def oracle_index(W):
    """The same kind of index, built from the truth: correct people, canonical kinds and values."""
    ix = Index()
    pid_of = {}
    for p in W.people:
        pid_of[p["id"]] = ix.person(p["full"])
    for n in W.notes:
        for pid, kind, value in n["facts"]:
            x = pid_of[pid]
            if kind in MW.RELS:
                ix.add(n["id"], x, kind, pid_of[value], link=pid_of[value])
            elif kind == "event":
                ix.add(n["id"], x, "event", f"{value[1]} {value[0]}")
            elif kind in MW.SLOTS:
                if value is None:
                    ix.add(n["id"], x, kind, "none")
                else:
                    ix.add(n["id"], x, kind, value)
            else:
                ix.add(n["id"], x, kind, str(value))
        stated = {pid for pid, _, _ in n["facts"]}
        for _, pid, _ in n["mentions"]:
            if pid not in stated:
                ix.add(n["id"], pid_of[pid], "mentioned", "-")
                stated.add(pid)
    return ix


# ============================================================================ the read side (B, nolinks, oracle)
def parse_cues(text):
    c = defaultdict(list)
    for line in text.splitlines():
        m = re.match(r"\s*[-*]?\s*(name|me|fact|link|ask|time)\s*:\s*(.+)", line, re.I)
        if m and m.group(2).strip():
            c[m.group(1).lower()].append(m.group(2).strip().strip('"'))
    return dict(c)


def month_of(text):
    t = text.lower()
    for i, mname in enumerate(MW.MONTHS):
        m = re.search(mname.lower() + r"\s+(\d{4})", t)
        if m:
            return f"{m.group(1)}-{i + 1:02d}"
    return None


class Reader:
    def __init__(self, ix, W, emb, links=True):
        self.ix, self.W, self.emb, self.links = ix, W, emb, links
        self.rows = ix.rows
        self.row_text = [f"{r['kind']}: {r['value']}" for r in self.rows]
        self.row_vec = emb(self.row_text) if self.rows else np.zeros((0, 384))
        text = {n["id"]: n["text"] for n in W.notes}            # the message's own words, for meaning matches
        self.note_vec = emb([text[r["note"]] for r in self.rows]) if self.rows else np.zeros((0, 384))
        self.by_pid = defaultdict(list)
        for i, r in enumerate(self.rows):
            self.by_pid[r["pid"]].append(i)
        self.date = {n["id"]: n["date"] for n in W.notes}

    def name_match(self, cue):
        cue_l = cue.lower().strip()
        base = cue_l.split(" from ")[0].strip()
        out = {}
        for pid, p in self.ix.people.items():
            s = 0
            if cue_l in p["names"] or base in p["names"]:
                s = 3 if (cue_l == p["full"].lower() or base == p["full"].lower()) else 2
            elif any(base == nm.split()[0] for nm in p["names"] if not nm.startswith("my ")):
                s = 1
            if s:
                if " from " in cue_l:          # "Mira from work": prefer the one known from work
                    ctx = cue_l.split(" from ", 1)[1]
                    known = [self.rows[i]["value"].lower() for i in self.by_pid[pid] if self.rows[i]["kind"] ==
                             "known from"]
                    s += 2 if any(w in k for k in known for w in ctx.split() if len(w) > 3) else 0
                out[pid] = s
        return out

    def fact_scores(self, cue):
        if not self.rows:
            return {}
        v = self.emb([cue])[0]
        sims = np.maximum(self.row_vec @ v, self.note_vec @ v)
        best = {}
        for i, s in enumerate(sims):
            pid = self.rows[i]["pid"]
            if s > best.get(pid, -1):
                best[pid] = float(s)
        return best

    def notes_for(self, pid, ask_cue, time_cue, k=PER_PERSON):
        idx = self.by_pid.get(pid, [])
        if not idx:
            return []
        if ask_cue:
            sims = self.row_vec[idx] @ self.emb([ask_cue])[0]
            order = [idx[j] for j in np.argsort(-sims)]
        else:
            order = idx
        naming = [i for i in idx if self.rows[i]["kind"] in ("relation to me", "known from", "nickname")]
        events = [i for i in idx if "event" in self.rows[i]["kind"]]
        pick = naming[:3]
        want_event = bool(time_cue) or (ask_cue and any(w in ask_cue.lower() for w in ("when", "last", "did", "do")))
        if want_event:
            ym = month_of(time_cue or "")
            ev = [i for i in events if not ym or self.rows[i]["value"].startswith(ym) or
                  self.date[self.rows[i]["note"]].startswith(ym)]
            pick += sorted(ev, key=lambda i: self.rows[i]["note"])[-15:]
        pick += order
        out = []
        for i in pick:
            if self.rows[i]["note"] not in out:
                out.append(self.rows[i]["note"])
            if len(out) >= k:
                break
        return out

    def penalty(self, pid):
        """Fan correction: a person with hundreds of rows matches any description a little (ACT-R's S - ln fan)."""
        return FAN * math.log(1 + len(self.by_pid.get(pid, [])))

    def link_targets(self, anchor, link):
        """Follow one link from the anchor: the best-matching link rows (kind and message, both directions), no fixed
        threshold; every partner within 0.05 of the best is shown, so the reader can check the direction."""
        lv = self.emb([link])[0]
        cand = []
        for i, r in enumerate(self.rows):
            if r["link"] and (r["pid"] == anchor or r["link"] == anchor):
                other = r["link"] if r["pid"] == anchor else r["pid"]
                sim = max(float(self.row_vec[i] @ lv), float(self.note_vec[i] @ lv))
                sim += 0.2 if any(w in r["kind"] for w in norm(link) if len(w) > 3) else 0
                cand.append((sim, other, r["note"]))
        if not cand:
            return []
        best = max(c[0] for c in cand)
        return [(o, n) for sim, o, n in sorted(cand, reverse=True) if sim >= best - 0.05][:3]

    def matching_notes(self, pid, cues, k):
        """A person's naming rows plus the rows that best match the described facts or what is asked."""
        idx = self.by_pid.get(pid, [])
        if not idx:
            return []
        vs = self.emb(cues)
        sims = np.max(np.maximum(self.row_vec[idx] @ vs.T, self.note_vec[idx] @ vs.T), axis=1)
        naming = [i for i in idx if self.rows[i]["kind"] in ("relation to me", "known from", "nickname")][:2]
        out = []
        for i in naming + [idx[j] for j in np.argsort(-sims)]:
            if self.rows[i]["note"] not in out:
                out.append(self.rows[i]["note"])
            if len(out) >= k:
                break
        return out

    def retrieve(self, cues, question):
        # a "name" clue that is nobody's name ("name: axolotl") is a described fact (dev phase: retrieval, allowed)
        given = [nm for nm in cues.get("name", []) if self.name_match(nm)]
        moved = [nm for nm in cues.get("name", []) if nm not in given]
        names = given + [f"my {m.replace('my ', '')}" for m in cues.get("me", [])]
        facts, link = cues.get("fact", []) + moved, (cues.get("link") or [None])[0]
        if not names and link:                    # "link: archery club" with no one to go through: also a fact
            facts, link = facts + cues.get("link", []), None
        ask_cue = " ".join(cues.get("ask", [])) or question
        time_cue = " ".join(cues.get("time", [])) or (question if month_of(question) else "")
        score = Counter()
        for nm in names:
            for pid, s in self.name_match(nm).items():
                score[pid] += s
        if facts:
            fs = [self.fact_scores(f) for f in facts]
            pool = list(score) if score else list(self.ix.people)
            for pid in pool:                                          # every described fact must match
                score[pid] += 5 * (min(f.get(pid, 0) for f in fs) - self.penalty(pid))
        notes = []
        ym = month_of(time_cue) if time_cue else None
        if not names and facts and ym:                                # "who did I go hiking with in July 2025?"
            fv = self.emb([" ".join(facts)])[0]
            words = [w for w in norm(" ".join(facts)) if len(w) > 3]
            for i, r in enumerate(self.rows):
                if "event" in r["kind"] and (r["value"].startswith(ym) or self.date[r["note"]].startswith(ym)) and \
                        (any(w[:4] in r["value"].lower() for w in words) or
                         max(float(self.row_vec[i] @ fv), float(self.note_vec[i] @ fv)) > 0.5):
                    notes.append(r["note"])
                    notes += self.notes_for(r["pid"], "relation to me known from", "", k=2)
        num = lambda x: int(x[1:])
        ranked = sorted(score, key=lambda x: (-score[x], num(x)))
        if not ranked:                                                # no clue matched: rows nearest the question
            if self.rows:
                sims = self.row_vec @ self.emb([question])[0]
                for i in np.argsort(-sims)[:MAX_NOTES]:
                    if self.rows[i]["note"] not in notes:
                        notes.append(self.rows[i]["note"])
            return sorted(notes)[:MAX_NOTES], []
        if facts and not names:                                       # described people: show the best few, each with
            targets = ranked[:FACT_TARGETS]                           # only the rows that match (desc / who)
            for t in targets:
                notes += self.matching_notes(t, facts + [ask_cue], k=8)
            out = list(dict.fromkeys(notes))[:MAX_NOTES]
            return sorted(out), targets
        top = ranked[:1]
        if len(ranked) > 1 and score[ranked[1]] >= score[ranked[0]] - 0.5:
            top = ranked[:2]                                          # too close to call: show both (ambiguity)
        targets = top
        if link and self.links:
            tg = [x for a in top for x in self.link_targets(a, link)]
            if tg:
                notes += [n for _, n in tg]
                targets = list(dict.fromkeys(p for p, _ in tg))[:3]
                for a in top:
                    notes += self.notes_for(a, "relation to me known from", "", k=3)
        for t in targets:
            if facts:
                notes += self.matching_notes(t, facts + [ask_cue], k=PER_PERSON)
            else:
                notes += self.notes_for(t, ask_cue, time_cue)
        out = list(dict.fromkeys(notes))[:MAX_NOTES]
        return sorted(out), targets


def answer_prompt(W, note_ids, q):
    by = {n["id"]: n for n in W.notes}
    lines = [f"[{dshow(by[i]['date'])}] {by[i]['text']}" for i in sorted(note_ids) if i in by and
             i not in W.deleted_ids]
    return ANSWER.format(notes="\n".join(lines) or "(no notes found)", today=TODAY, q=q["q"])


# ============================================================================ C: search agent
class Search:
    def __init__(self, W, emb):
        self.notes = [n for n in W.notes if n["id"] not in W.deleted_ids]
        self.bm = BM25([n["text"] for n in self.notes])
        self.vec = emb([n["text"] for n in self.notes])
        self.emb = emb
        self.date = {n["id"]: n["date"] for n in W.notes}

    def top(self, query, k=AGENT_K, skip=()):
        b = self.bm.top(query, 100)                                      # (BM25.top returns indices in notebook order)
        q = [t for t in pnorm(query).split() if t not in STOP]     # the same words BM25 indexed
        bm_scores = []
        for i in b:
            tf, d = self.bm.tf[i], self.bm.toks[i]
            bm_scores.append((sum(self.bm.idf.get(t, 0) * tf[t] * (self.bm.k1 + 1) / (tf[t] + self.bm.k1 * (
                1 - self.bm.b + self.bm.b * len(d) / self.bm.avg)) for t in set(q) if t in tf), i))
        bm_rank = [i for _, i in sorted(bm_scores, reverse=True)]
        sims = self.vec @ self.emb([query])[0]
        em_rank = list(np.argsort(-sims)[:100])
        rrf = Counter()
        for rank in (bm_rank, em_rank):
            for k_, i in enumerate(rank):
                rrf[int(i)] += 1 / (60 + k_)
        out = [self.notes[i]["id"] for i, _ in rrf.most_common()]
        ym = month_of(query)
        if ym:                                                           # "... in July 2025": that month only
            inmonth = [i for i in out if self.date[i].startswith(ym)]
            out = inmonth + [i for i in out if not self.date[i].startswith(ym)] if inmonth else out
        return [i for i in out if i not in skip][:k]


def run_agent(llm, S, W, q, think, seed):
    found, steps, tokens = list(S.top(q["q"])), [], 0
    by = {n["id"]: n for n in W.notes}
    for left in range(AGENT_ROUNDS, -1, -1):
        notes = "\n".join(f"[{dshow(by[i]['date'])}] {by[i]['text']}" for i in sorted(found))
        if left == 0:
            r = ask(llm, ANSWER.format(notes=notes, today=TODAY, q=q["q"]), THINK if think else NOTHINK, think, seed)
            steps.append({"final": True, **{k: r[k] for k in ("text", "cut", "completion_tokens")}})
            return r, found, steps
        r = ask(llm, AGENT.format(notes=notes, today=TODAY, q=q["q"], left=left), THINK if think else NOTHINK, think,
                seed + left)
        steps.append({k: r[k] for k in ("text", "cut", "completion_tokens")})
        t = r["text"]
        m = re.search(r"SEARCH:\s*(.+)", t)
        if m and "ANSWER:" not in t.split("SEARCH:")[0]:
            found += S.top(m.group(1).strip().splitlines()[0], k=AGENT_MORE, skip=set(found))   # 15 new each time
            found = found[:AGENT_MAX]
            continue
        a = re.search(r"ANSWER:\s*(.+)", t, re.S)
        r = dict(r, text=(a.group(1).strip() if a else t))
        return r, found, steps
    return r, found, steps


def run_ccues(llm, S, W, q, cue_text, think, seed):
    """Search at B's cost: the question and each of B's clue lines become one search each; their results are merged in
    turn up to 60 messages; one answer call. No extra thinking steps."""
    qs = [q["q"]] + [line.split(":", 1)[1].strip() for line in cue_text.splitlines()
                     if ":" in line and line.split(":", 1)[0].strip().lower() in ("name", "me", "fact", "link", "time")
                     and line.split(":", 1)[1].strip()]
    lists = [S.top(x, k=AGENT_K) for x in qs]
    found = []
    for i in range(AGENT_K):
        for L in lists:
            if i < len(L) and L[i] not in found:
                found.append(L[i])
    found = found[:MAX_NOTES]
    r = ask(llm, answer_prompt(W, found, q), THINK if think else NOTHINK, think, seed)
    return r, found


# ============================================================================ pages (the reading ceiling)
def pages(W, q):
    rng = random.Random(zlib.crc32(q["qid"].encode()))
    gold = set(q["notes"])
    about = set([q["person"]] if q["person"] is not None else []) | set(q.get("people", [])) | \
        ({q["anchor"]} if q.get("anchor") is not None else set())
    if q["person"] is not None:
        same = [p["id"] for p in W.people if p["first"] == W.people[q["person"]]["first"]]
        about |= set(same)
    pool = [n["id"] for n in W.notes if n["id"] not in gold and n["id"] not in W.deleted_ids and
            any(m[1] in about for m in n["mentions"])]
    if q["kind"] == "upd":                         # the whole history of the asked fact belongs in the pages
        gold |= set(W.current(q["person"], q["slot"])[2])
    core = set([q["person"]] if q["person"] is not None else []) | set(q.get("people", [])) | \
        ({q["anchor"]} if q.get("anchor") is not None else set())
    gold |= {n["id"] for n in W.notes if n["type"] in ("intro", "nick") and n["id"] not in W.deleted_ids and
             any(m[1] in core for m in n["mentions"])}   # who they are: introduction, nickname (dev phase: retrieval)
    return sorted(gold | set(rng.sample(pool, min(20, len(pool)))))


# ============================================================================ scoring
def has_key(text, key):
    """A value key in a text: keys of up to 4 letters must be whole words ("bee" not in "been", "cat" not in "category",
    plural allowed); longer keys are stems matched at a word start ("translat" in "translates")."""
    k = key.strip().lower()
    tail = r"(s|es)?(?![a-z])" if len(k) <= 4 else ""
    return re.search(r"(?<![a-z])" + re.escape(k) + tail, text.lower()) is not None


# Verb forms the answer keys lacked ("They fish." for fishing), found by reading dev answers (dev phase). Used for
# scoring answers only: the world generator also uses its keys (to choose deletions), so they stay as reviewed there.
SCORE_EXTRA = {"climbing": ["climb"], "fishing": ["fish", "fisher"], "rowing": ["row"], "pottery": ["potter"],
               "archery": ["archer"], "watercolour painting": ["paint"], "baker": ["bake"],
               "primary school teacher": ["teach"]}


def answer_keys(v, keys):
    return list(keys) + SCORE_EXTRA.get(v, [])


def named_values(slot, text):
    out = []
    for c, alt, keys in MW.SLOTS[slot]["vals"]:
        if any(has_key(text, k) for k in answer_keys(c, keys)):
            out.append(c)
    return out


def people_named(W, text):
    t = text.lower()
    return {p["id"] for p in W.people if p["full"].lower() in t}


DATE_PATS = [r"(\d{4})-(\d{2})-(\d{2})"]


def dates_in(text):
    t, out = text.lower(), set()
    for m in re.finditer(r"(\d{4})-(\d{1,2})-(\d{1,2})", t):
        out.add((int(m.group(1)), int(m.group(2)), int(m.group(3))))
    for m in re.finditer(r"\b(\d{1,2})/(\d{1,2})/(\d{4})\b", t):                  # 28/07/2026 (day first)
        out.add((int(m.group(3)), int(m.group(2)), int(m.group(1))))
    for i, mn in enumerate(MW.MONTHS):
        mn = mn.lower()
        for m in re.finditer(r"(?<!\d)(\d{1,2})(?:st|nd|rd|th)?\s+(?:of\s+)?" + mn + r"(?:\s*,?\s*(\d{4}))?", t):
            out.add((int(m.group(2)) if m.group(2) else None, i + 1, int(m.group(1))))
        for m in re.finditer(mn + r"\s+(\d{1,2})(?!\d)(?:st|nd|rd|th)?(?:\s*,?\s*(\d{4}))?", t):
            out.add((int(m.group(2)) if m.group(2) else None, i + 1, int(m.group(1))))
    return out


NONE_RE = re.compile(r"\b(no longer|any ?more|gave\b.*\baway|sold|stopped|quit|dropped|cleared|none|no pets?|"
                     r"no car|no plants|not working|isn't working|got rid|(doesn't|does not|don't|do not) "
                     r"(have|drive|play|work|own|grow|keep))\b")


def history_ok(ans, gold, named, hist):
    """Earlier values may be named only as earlier ("flute, previously bass guitar"): each one must follow a word that
    marks it as old, and the current value must not be hedged with "or"."""
    t = ans.lower()
    for v in named:
        if v == gold:
            continue
        if v not in hist:
            return False
        pos = min((m.start() for k in answer_keys(v, MW.value_keys_any(v)) for m in re.finditer(r"(?<![a-z])" + re.escape(k.strip()),
                                                                                    t)), default=None)
        if pos is None or not OLD_MARK.search(t[max(0, pos - 40):pos]):
            return False
    return True


def score(W, q, ans):
    """Strict where leniency would reward a missing or hedged memory: an empty (cut-off) answer is always wrong; a
    deleted or never-stated fact needs an explicit "not in my notes"; a retraction needs an explicit "no longer"."""
    t = ans.lower()
    k = q["kind"]
    abstain = any(a in t for a in ABSTAIN)
    res = {"correct": False, "leak": False, "stale": False}
    if not t.strip():
        return res
    if k in ("named", "role", "nick", "fname_ctx", "desc", "two", "upd"):
        named = named_values(q["slot"], ans)
        hist = set(q.get("old", []))
        res["named"] = named
        res["correct"] = q["gold"] in named and history_ok(ans, q["gold"], named, hist) and not abstain
        res["stale"] = q["gold"] not in named and bool(set(named) & hist)
    elif k == "retract":
        named = named_values(q["slot"], ans)
        res["named"] = named
        res["correct"] = (bool(NONE_RE.search(t)) and not abstain and "still" not in t and
                          not (set(named) - set(q.get("old", []))))
    elif k in ("deleted", "never"):
        named = named_values(q["slot"], ans)
        res["named"] = named
        res["leak"] = k == "deleted" and q["leak"] in named
        res["guess"] = bool(named)
        res["correct"] = abstain and not named
    elif k == "amb":
        ids = set(q["people"])
        first = W.people[q["people"][0]]["first"].lower()
        asks = bool(re.search(r"\bwhich (one|of)\b|\bdo you mean\b|\bwhich " + re.escape(first) + r"\b", t))
        res["correct"] = asks or len(people_named(W, ans) & ids) >= 2
    elif k in ("who", "event_who"):
        got = people_named(W, ans)
        p = W.people[q["person"]]
        role = W.role_now(p)
        ok = (q["person"] in got or
              (role and re.search(rf"\b(my|your) {re.escape(role)}\b", t)) or
              (p["nick"] and re.search(rf"\b{re.escape(p['nick'].lower())}\b", t)) or
              (p["first"].lower() in norm(ans) and sum(x["first"] == p["first"] for x in W.people) == 1))
        res["correct"] = (bool(ok) and not (got - {q["person"]}) and not HEDGE.search(t) and
                          not HEDGE_NAMES.search(re.sub(r"\([^)]*\)", "", ans)) and not abstain)
    elif k == "event_last":
        y, m, d = map(int, q["gold"].split("-"))
        ds = {(yy or y, mm, dd) for yy, mm, dd in dates_in(ans)}
        res["correct"] = (y, m, d) in ds and max(ds) == (y, m, d)        # the gold date, named as the latest
    elif k == "event_what":
        acts = [a for a, keys in ACT_KEYS.items() if any(kk in t for kk in keys)]
        res["correct"] = acts == [q["gold"]]
    return res


# ============================================================================ filing quality (B's write side)
ME_NAMES = {"me", "i", "myself", "user", "the user", "the writer", "me (the writer)", "writer"}


def write_quality(W, ix):
    """Who each index person really is (the majority of the true people in the single-person messages its rows come
    from). Merges are counted on fact rows only (not links, not "mentioned" tags, not a "me" person), on messages that
    state a fact:
      wrong merges  = fact rows filed under an index person who is not mentioned in the row's message (a "Kofi's
                      flatmate" row filed under Kofi is not a merge: Kofi is mentioned);
      hard merges   = the same, on messages that name someone without the full name while a same- or near-name person
                      was already known (the cases that need telling apart);
      filing by mention style = of the true facts the writer wrote down, the share filed under the right person, by how
                      that person was mentioned;
      link precision, lure intrusion (a row carrying a lure's value), people split into several ids, facts filed."""
    truth_people = {n["id"]: {m[1] for m in n["mentions"]} for n in W.notes}
    owners = {n["id"]: {x for pid, kind, value in n["facts"] for x in ((pid, value) if kind in MW.RELS else (pid,))}
              for n in W.notes}                     # a fact row belongs to the person the fact is about
    me = {pid for pid, p in ix.people.items() if p["full"].lower().strip(" .") in ME_NAMES}
    rows = [r for r in ix.rows if r["pid"] not in me]
    votes = defaultdict(Counter)
    for r in rows:
        ppl = truth_people.get(r["note"], set())
        if len(ppl) == 1:
            votes[r["pid"]][next(iter(ppl))] += 1
    who = {pid: c.most_common(1)[0][0] for pid, c in votes.items()}
    fact_notes = {n["id"] for n in W.notes if n["facts"]}
    fact_rows = [r for r in rows if r["pid"] in who and not r["link"] and r["kind"] != "mentioned" and
                 r["note"] in fact_notes]
    wrong = [r for r in fact_rows if who[r["pid"]] not in owners.get(r["note"], set())]
    conf = {n["id"] for n in W.notes if n.get("confusable") or any(m[2] in ("via", "source") for m in n["mentions"])}
    hard = [r for r in fact_rows if r["note"] in conf]
    hard_wrong = [r for r in hard if who[r["pid"]] not in owners.get(r["note"], set())]
    rows_by_note = defaultdict(list)
    for r in rows:
        rows_by_note[r["note"]].append(r)
    by_style, got, facts = defaultdict(lambda: [0, 0]), 0, 0
    for n in W.notes:
        style = {m[1]: m[2] for m in n["mentions"]}
        for pid, s, v in n["facts"]:
            if s not in MW.SLOTS or v is None:
                continue
            facts += 1
            keys = MW.value_keys(s, v)
            match = [r for r in rows_by_note[n["id"]] if any(has_key(r["value"], k) for k in keys)]
            if match:
                st = style.get(pid, "?")
                ok = any(who.get(r["pid"]) == pid for r in match)
                by_style[st][0] += ok
                by_style[st][1] += 1
                got += ok
    links = [r for r in rows if r["pid"] in who and r["link"] and r["link"] in who]
    pairs = {frozenset((p["id"], b)) for p in W.people for rel, b, way in p["links"]}
    link_ok = sum(frozenset((who[r["pid"]], who[r["link"]])) in pairs for r in links)
    lures = [n for n in W.notes if n.get("lure")]
    intr = sum(any(r["value"].lower() != "none" and r["kind"] != "mentioned" and
                   any(has_key(r["value"], k) for k in MW.value_keys(n["lure"][0], n["lure"][1]))
                   for r in rows_by_note[n["id"]]) for n in lures)
    ids_per_person = Counter(who.values())
    return {"index_people": len(ix.people), "true_people": len(W.people), "rows": len(ix.rows),
            "me_rows": len(ix.rows) - len(rows), "fact_rows": len(fact_rows),
            "wrong_merge_pct": 100 * len(wrong) / max(1, len(fact_rows)),
            "hard_merge_pct": 100 * len(hard_wrong) / max(1, len(hard)), "hard_rows": len(hard),
            "filed_right_by_style": {k: round(100 * a / b, 1) for k, (a, b) in sorted(by_style.items())},
            "filed_n_by_style": {k: b for k, (a, b) in sorted(by_style.items())},
            "people_split_into_several_ids": sum(1 for c in ids_per_person.values() if c > 1),
            "facts_filed_pct": 100 * got / max(1, facts),
            "link_precision_pct": 100 * link_ok / max(1, len(links)), "link_rows": len(links),
            "lure_intrusion_pct": 100 * intr / max(1, len(lures)), "who": who}


def forget_test(W, ix, reader):
    """'Forget Kofi': find the person by full name in the index, remove every message filed under them. Recall = the
    share of the messages that truly mention them (any way: name, pronoun, "Kofi's flatmate", as a source) that go;
    collateral = other messages removed with them. Run on the 10 close people and 10 people with a same first name."""
    firsts = Counter(p["first"] for p in W.people)
    targets = [p for p in W.people if p["close"]] + [p for p in W.people if firsts[p["first"]] > 1][:10]
    rec, coll, tot = [], 0, 0
    for p in targets:
        ids = [pid for pid, sc in reader.name_match(p["full"]).items() if sc >= 3]
        names = {p["full"].lower()} | {nm for pid in ids for nm in ix.people[pid]["names"]
                                       if len(nm.split()) > 1 and not nm.startswith("my ")}
        nick = [nm for pid in ids for nm in ix.people[pid]["names"] if len(nm.split()) == 1 and
                sum(nm in q["names"] for q in ix.people.values()) == 1 and nm != p["first"].lower()]
        removed = {r["note"] for r in ix.rows if r["pid"] in ids}
        removed |= {n["id"] for n in W.notes if any(x in n["text"].lower() for x in names) or
                    any(re.search(r"(?<![a-z])" + re.escape(x) + r"(?![a-z])", n["text"].lower()) for x in nick)}
        truth = {n["id"] for n in W.notes if any(m[1] == p["id"] for m in n["mentions"]) and n["id"] not in
                 W.deleted_ids}
        if not truth:                                    # only with --dev-limit: not mentioned yet (no-op on a full world)
            continue
        rec.append(len(removed & truth) / max(1, len(truth)))
        coll += len(removed - truth)
        tot += len(removed)
    return {"forget_recall_pct": 100 * float(np.mean(rec)), "forget_worst_pct": 100 * float(np.min(rec)),
            "forget_collateral_pct": 100 * coll / max(1, tot), "forget_people": len(rec)}


def deletion_audit(W, ix, who):
    """After deleting the 100 messages: rows still carrying a deleted value for that person whose own (cited) message
    does not contain the value, i.e. rows that came from the deleted message under a wrong message number. A row whose
    own message does contain the value is a misfiled fact of someone else, counted as a merge, not as a leak."""
    text = {n["id"]: n["text"].lower() for n in W.notes}
    left = 0
    for pid, s_, nid, val in W.deleted:
        keys = MW.value_keys(s_, val)
        left += any(who.get(r["pid"]) == pid and any(has_key(r["value"], k) for k in keys) and
                    not any(has_key(text.get(r["note"], ""), k) for k in keys) for r in ix.rows)
    return left


# ============================================================================ the stub (bookkeeping check, no model)
class Stub:
    """Plays the model from the truth: a writer with 5% missed and 1% misfiled facts, clue lines from the
    question, and a perfect reader that answers right only when the messages it needs are in the prompt. So the
    stub's accuracy measures the retrieval code, and every count, score and line is checked without a GPU."""

    def __init__(self, W):
        self.W, self.model, self.served = W, "stub", ["stub"]
        self.byq = {q["q"]: q for q in W.questions}
        self.rng, self.lock = random.Random(7), threading.Lock()
        self.seen_new = set()

    def request(self, method, path, body):
        p = body["messages"][0]["content"]
        with self.lock:
            if p.startswith("You keep the index"):
                t = self.write(p)
            elif p.startswith("Someone asks"):
                t = self.cues(p)
            else:
                t = self.answer(p)
        return {"choices": [{"message": {"content": t, "reasoning": "stub"}, "finish_reason": "stop"}],
                "usage": {"prompt_tokens": len(p) // 4, "completion_tokens": len(t) // 4 + 5}}

    def write(self, p):
        """A writer that can only use ids for people shown in its list (or named in full in the message). Otherwise it
        does what a real model would: files "Kofi's flatmate" under Kofi, a bare first name under a listed namesake, or
        writes a NEW person (a split). Also writes link rows, "mentioned" tags and, sometimes, a row about "me"."""
        people = p.split("People already in the index", 1)[1].split("Earlier messages", 1)[0]
        visible = set(re.findall(r"P\d+: ([^;\n]+)", people))
        new = p.split("New messages:\n", 1)[1].split("\n\nWrite one line", 1)[0]
        out = []
        for line in new.splitlines():
            nid = int(line.split()[0][1:])
            n = self.W.notes[nid]
            style = {m[1]: m[2] for m in n["mentions"]}
            anchor = next((m[1] for m in n["mentions"] if m[2] == "via_anchor"), None)

            def who_for(pid):
                full = self.W.people[pid]["full"]
                if full in visible or full in n["text"]:
                    return full if full in visible else f"NEW: {full}"
                if style.get(pid) == "via" and anchor is not None and self.W.people[anchor]["full"] in visible:
                    return self.W.people[anchor]["full"]                       # files the flatmate's fact under Kofi
                first = self.W.people[pid]["first"]
                namesakes = [v for v in visible if v.split()[0] == first]
                if namesakes:
                    return namesakes[0]                                         # a namesake on the list
                return f"NEW: {first} ({nid})"                                  # a split
            stated = set()
            for pid, kind, value in n["facts"]:
                if self.rng.random() < 0.05:
                    continue
                w = who_for(pid)
                if self.rng.random() < 0.01:
                    w = self.rng.choice(sorted(visible)) if visible else w
                if w.startswith("NEW: ") and "(" not in w:
                    self.seen_new.add(w[5:])
                stated.add(pid)
                if kind in MW.RELS:
                    v = who_for(value)
                    if v.startswith("NEW: ") and "(" not in v:
                        self.seen_new.add(v[5:])
                elif kind == "event":
                    v = f"{value[1]} {value[0]}"
                else:
                    v = "none" if value is None else str(value)
                out.append(f"#{nid} | {w} | {kind} | {v}")
            if anchor is not None and self.rng.random() < 0.5:                  # the link it used to resolve the name
                tgt = next(m[1] for m in n["mentions"] if m[2] == "via")
                out.append(f"#{nid} | {who_for(anchor)} | link | {who_for(tgt)}")
            for _, pid, st in n["mentions"]:
                if pid not in stated and st != "via_anchor":
                    out.append(f"#{nid} | {who_for(pid)} | mentioned | -")
                    stated.add(pid)
            if n["type"] == "me" and self.rng.random() < 0.3:
                out.append(f"#{nid} | NEW: Me | {n['lure'][0]} | {n['lure'][1]}")
        return "\n".join(out)

    def cues(self, p):
        q = self.byq[p.split("Question: ", 1)[1].strip()]
        W, k = self.W, q["kind"]
        lines = []
        txt = q["q"]
        if q["person"] is not None and k in ("named", "upd", "retract", "deleted") and not txt.lower().count("my "):
            lines.append(f"name: {W.people[q['person']]['full']}")
        roles = [r_ for r_ in sorted(MW.CLOSE_ROLES, key=len, reverse=True) if f"my {r_}" in txt.lower()]
        if roles and k != "two":
            lines.append(f"me: {roles[0]}")
        if k == "amb":
            lines.append(f"name: {W.people[q['people'][0]]['first']}")
        if k == "nick":
            lines.append(f"name: {W.people[q['person']]['nick']}")
        if k == "fname_ctx":
            lines.append(f"name: {txt.split(' does ')[1].split(' do')[0] if ' does ' in txt else ''}")
        if k in ("desc", "who"):
            body = re.split(r"the person who |Who ", txt)[-1].rstrip("?")
            body = re.split(r" (?:do|live|drive|play|have|grow)\b", body)[0] if k == "desc" else body
            for part in body.split(" and "):
                lines.append(f"fact: {part.strip()}")
        if k == "two":
            a = W.people[q["anchor"]]
            lines.append(f"me: {a['role']}" if a["role"] else f"name: {a['full']}")
            lines.append(f"link: {MW.RELS[q['rel']][3]}")
        if k in ("event_last", "event_what", "event_who"):
            if k == "event_who":
                lines.append(f"fact: {q.get('act', '')}")
            elif W.people[q["person"]]["role"] is None:
                lines.append(f"name: {W.people[q['person']]['full']}")
            mo = month_of(txt)
            lines.append(f"time: {txt.split(' in ')[-1].rstrip('?') if mo else 'last'}")
        lines.append(f"ask: {q['slot'] or 'who'}")
        return "\n".join(lines)

    def answer(self, p):
        if p.startswith("You answer questions"):
            q = self.byq[p.split("Question: ", 1)[1].split("\n")[0].strip()]
            if "1 more time" not in p and not all(self.W.notes[n]["text"] in p for n in self.key_notes(q)):
                return f"SEARCH: {q['q']}"
            return "ANSWER: " + self.gold_text(q, p)
        q = self.byq[p.split("Question: ", 1)[1].split("\n")[0].strip()]
        return self.gold_text(q, p)

    def key_notes(self, q):
        """The messages an answer needs (naming messages excluded: a reader can tie names together from the rest)."""
        key = [n for n in q["notes"] if self.W.notes[n]["type"] not in ("intro", "nick")]
        return key or q["notes"]

    def gold_text(self, q, prompt=None):
        if prompt is not None and not all(self.W.notes[n]["text"] in prompt for n in self.key_notes(q)):
            return "not in my notes"
        k = q["kind"]
        if k in ("deleted", "never"):
            return "not in my notes"
        if k == "retract":
            return "None any more - that was taken back."
        if k == "amb":
            return "Which one do you mean?"
        if k in ("who", "event_who"):
            return self.W.people[q["person"]]["full"]
        if k == "event_last":
            y, m, d = q["gold"].split("-")
            return f"{int(d)} {MW.MONTHS[int(m) - 1]} {y}"
        return str(q["gold"])


